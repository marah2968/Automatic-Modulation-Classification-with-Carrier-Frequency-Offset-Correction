    hidden1 = Dense(500, activation='relu')(inputs)
    dropout1 = Dropout(0.2)(hidden1)
    hidden2 = Dense(600, activation='relu')(dropout1)
    dropout2 = Dropout(0.2)(hidden2)
    hidden3= Dense(300, activation='relu')(dropout2)
    dropout3 = Dropout(0.2)(hidden3)
    outputs = Dense(1, activation='linear')(dropout3)
    model = Model(inputs=inputs, outputs=outputs)
