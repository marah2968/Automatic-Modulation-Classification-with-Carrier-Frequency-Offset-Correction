function y = riceanMultipath(x, fs)
    persistent ricianChan
    
    % Initialize Rician channel object if it doesn't exist
    if isempty(ricianChan)
        ricianChan = comm.RicianChannel(...
            'SampleRate', fs, ...
            'PathDelays', [0.0 0.9 1.7], ...
            'AveragePathGains', [1 0.8 0.3], ...
            'KFactor', 4, ...
            'DirectPathDopplerShift', 0, ...
            'DirectPathInitialPhase', 0, ...
            'MaximumDopplerShift', 0, ...
            'DopplerSpectrum', doppler('Jakes'), ...
            'FadingTechnique', 'Sum of sinusoids', ...
            'NumSinusoids', 8, ...
            'RandomStream', 'mt19937ar with seed', ...
            'Seed', 73, ...
            'PathGainsOutputPort', true);
        
        % Uncomment if visualization is needed
        % ricianChan.Visualization = 'Impulse response'; 
        % ricianChan.Visualization = 'Frequency response';
    end

    % Apply Rician channel to input signal x
    y = ricianChan(x);
    
    % Optionally, you can add pause() to observe the effect
    % pause();
end
