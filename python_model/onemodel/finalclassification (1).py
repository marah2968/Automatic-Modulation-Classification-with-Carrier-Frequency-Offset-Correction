def CNN(input_shape=(128, 1), num_classes=11):
    # Define inputs
    input1 = Input(shape=input_shape, name='input1')
    input2 = Input(shape=input_shape, name='input2')
    input=concatenate([input1,input2])
    x=Conv1D(64, kernel_size=3 ,activation='relu')(input)
    x=MaxPooling1D(pool_size=2)(x)
    x=Dropout(0.3)(x)
    x=Conv1D(128, kernel_size=3, activation='relu')(x)
    x=MaxPooling1D(pool_size=2)(x)
    x=Dropout(0.3)(x)
    x=Conv1D(256, kernel_size=3, activation='relu')(x)
    x=MaxPooling1D(pool_size=2)(x)
    x=Dropout(0.3)(x)
    # Flatten the output
    x = Flatten()(x)
    # Dense layer with 512 neurons
    x = Dense(512, activation='relu')(x)
    x= Dropout(0.3)(x)
    # Output layer with softmax activation
    output = Dense(num_classes, activation='softmax')(x)

    # Create model
    model = Model(inputs=[input1, input2], outputs=output)

    return model

