def cal1(x_degrees):
    x_tensor = tf.convert_to_tensor(x_degrees, dtype=tf.float32)

    w = tf.concat([x_tensor * (i + 1) for i in range(128)], axis=-1)

    y = tf.cos(w )

    return tf.expand_dims(y, axis=-1)  # Expand dimensions to (None, 128, 1)

def cal2(x_degrees):
    x_tensor = tf.convert_to_tensor(x_degrees, dtype=tf.float32)


    w = tf.concat([x_tensor * (i + 1) for i in range(128)], axis=-1)  #

    y = tf.sin(w )

    return tf.expand_dims(y, axis=-1)

def CNN(input_shape=(128, 1), num_classes=11):
    # Define inputs
    input1 = Input(shape=input_shape, name='input1')
    input2 = Input(shape=input_shape, name='input2')
    input=concatenate([input1,input2])
    # Perform initial operations as described
    x1 = Flatten()(input)
    x1= Dense(80, name='fc1')(x1)
    x1 = Activation('relu')(x1)
    x1 = Dense(1, name='fc3')(x1)
    x1 = Activation('linear')(x1)

    cos1= Lambda(cal1)(x1)
    sin1 = Lambda(cal2)(x1)
    x11 = Multiply()([input1, cos1])
    x12 = Multiply()([input2, sin1])
    x21 = Multiply()([input2, cos1])
    x22 = Multiply()([input1, sin1])
    y1 = Add()([x11,x12])
    y2 = Subtract()([x21,x22])
    y1   = Reshape(target_shape=(128, 1), name='reshape1')(y1)
    y2 = Reshape(target_shape=(128, 1), name='reshape2')(y2)
    x11 = concatenate([y1,y2,input1,input2])


    # Start convolutional layers
    # The following layers operate on the concatenated result `x11`

    # First convolutional layer
    #x = Conv1D(filters=265, kernel_size=3, activation='relu')(x11)
    #x = MaxPooling1D(pool_size=2)(x)

    # Second convolutional layer
    #x = Conv1D(filters=80, kernel_size=3, activation='relu')(x)
    #x = MaxPooling1D(pool_size=2)(x)

    # Third convolutional layer
    #x = Conv1D(filters=50, kernel_size=2, activation='relu')(x)

   # x = Conv1D(filters=50, kernel_size=8, activation='relu')(x)
    x=Conv1D(64, kernel_size=3 ,activation='relu')(x11)
    x=MaxPooling1D(pool_size=2)(x)
    x=Dropout(0.3)(x)
    x=Conv1D(128, kernel_size=3, activation='relu')(x)
    x=MaxPooling1D(pool_size=2)(x)
    x=Dropout(0.3)(x)
    x=Conv1D(256, kernel_size=3, activation='relu')(x)
    x=MaxPooling1D(pool_size=2)(x)
    x=Dropout(0.3)(x)
    x = Flatten()(x)
    x = Dense(512, activation='relu')(x)
    x= Dropout(0.3)(x)
    output = Dense(num_classes, activation='softmax')(x)

    model = Model(inputs=[input1, input2], outputs=output)

    return model

