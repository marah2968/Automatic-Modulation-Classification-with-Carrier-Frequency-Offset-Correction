def plot_confusion_matrix(cm, title='Confusion matrix', cmap=plt.get_cmap("PuRd"), labels=[], save_filename=None):
    plt.figure(figsize=(6, 6))
    plt.imshow(cm * 100, interpolation='nearest', cmap=cmap)
    plt.colorbar()
    tick_marks = np.arange(len(labels))
    plt.xticks(tick_marks, labels, rotation=90, size=12)
    plt.yticks(tick_marks, labels, size=12)

    for i in range(len(tick_marks)):
        for j in range(len(tick_marks)):
            value = int(np.around(cm[i, j] * 100))
            if i != j:
                text = plt.text(j, i, f"{value}%", ha="center", va="center", fontsize=10)
            elif i == j:
                if value == 100:
                    text = plt.text(j, i, f"{value}%", ha="center", va="center", fontsize=7, color="white")
                else:
                    text = plt.text(j, i, f"{value}%", ha="center", va="center", fontsize=10, color="white")

    plt.tight_layout()
    plt.xlabel('Predicted Labels')
    plt.ylabel('True Labels')

def calculate_confusion_matrix(Y,Y_hat,classes):
    n_classes = len(classes)
    conf = np.zeros([n_classes,n_classes])
    confnorm = np.zeros([n_classes,n_classes])

    for k in range(0,Y.shape[0]):
        i = list(Y[k,:]).index(1)
        j = int(np.argmax(Y_hat[k,:]))
        conf[i,j] = conf[i,j] + 1

    for i in range(0,n_classes):
        confnorm[i,:] = conf[i,:] / np.sum(conf[i,:])
    # print(confnorm)

    right = np.sum(np.diag(conf))
    wrong = np.sum(conf) - right
    return confnorm,right,wrong

